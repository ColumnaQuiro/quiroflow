#!/usr/bin/env node
// Seeds ONE new account at the size of the live clinic, for measuring the
// reports and the dashboard against realistic volumes -- a report that is
// quick on a test account's twenty rows says nothing about 9,000
// appointments.
//
//   NUXT_PUBLIC_SUPABASE_URL=... NUXT_SUPABASE_SECRET_KEY=... node scripts/seed-report-scale.mjs
//
// Local Supabase only: it refuses any URL that is not a local one. Creates a
// fresh account every run (nothing is reset or deleted) and prints the owner's
// login, plus a practitioner's whose role narrows reports to their own
// figures. Rows are generated by scripts/lib/report-dataset.mjs, the same
// generator the dashboard characterization specs use at a smaller scale.
import { createClient } from '@supabase/supabase-js'
import { seedReportDataset, PROD_SCALE } from './lib/report-dataset.mjs'

// The well-known `supabase start` demo keys by default, as
// cypress/support/tasks/db.ts does -- they only ever open a local stack.
const url = process.env.NUXT_PUBLIC_SUPABASE_URL || 'http://127.0.0.1:54321'
const serviceKey =
  process.env.NUXT_SUPABASE_SECRET_KEY ||
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6InNlcnZpY2Vfcm9sZSIsImV4cCI6MTk4MzgxMjk5Nn0.EGIM96RAZx35lJzdJsyH-qQwv8Hdp7fsn3W0YpN81IU'
const anonKey =
  process.env.NUXT_PUBLIC_SUPABASE_KEY ||
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0'
if (!/^https?:\/\/(127\.0\.0\.1|localhost)(:\d+)?/.test(url)) {
  console.error(`Refusing to seed ${url}: local Supabase only.`)
  process.exit(1)
}

const opts = { auth: { autoRefreshToken: false, persistSession: false } }
const admin = createClient(url, serviceKey, opts)
const stamp = Date.now()
const password = 'Test1234!'

async function createUser(email) {
  const { data, error } = await admin.auth.admin.createUser({ email, password, email_confirm: true })
  if (error) throw error
  return data.user.id
}

const ownerEmail = `scale-owner-${stamp}@example.test`
await createUser(ownerEmail)
const ownerClient = createClient(url, anonKey, opts)
{
  const { error } = await ownerClient.auth.signInWithPassword({ email: ownerEmail, password })
  if (error) throw error
}
const { data: created, error: createErr } = await ownerClient.rpc('create_account_with_owner', {
  p_account_name: `Scale Clinic ${stamp}`,
  p_clinic_name: 'Centro',
  p_owner_name: 'Olga Owner',
})
if (createErr) throw createErr
const { account_id: accountId, clinic_id: clinicId } = created[0]

// Room on the plan for three practitioners, and a second clinic.
await admin.from('subscriptions').update({ extra_professionals: 2, growth_addon: true }).eq('account_id', accountId)
const { data: clinic2, error: clinicErr } = await admin.from('clinics').insert({ account_id: accountId, name: 'Norte' }).select('id').single()
if (clinicErr) throw clinicErr

const { data: owner } = await admin.from('team_members').select('id, full_name').eq('account_id', accountId).eq('is_owner', true).single()
await admin.from('team_members').update({ is_practitioner: true }).eq('id', owner.id)
const { data: practitionerRole } = await admin.from('account_roles').select('id').eq('account_id', accountId).eq('name', 'Practitioner').single()

const practitioners = [{ id: owner.id, name: owner.full_name }]
const logins = [{ who: 'owner', email: ownerEmail }]
for (const name of ['Beatriz Ferrando', 'Natacha Ruiz']) {
  const email = `scale-${name.split(' ')[0].toLowerCase()}-${stamp}@example.test`
  const userId = await createUser(email)
  const { data: tm, error } = await admin
    .from('team_members')
    .insert({ account_id: accountId, user_id: userId, full_name: name, role: 'practitioner', role_id: practitionerRole.id, is_owner: false, is_practitioner: true })
    .select('id')
    .single()
  if (error) throw error
  practitioners.push({ id: tm.id, name })
  logins.push({ who: name, email })
}

const counts = await seedReportDataset(admin, {
  accountId,
  clinicIds: [clinicId, clinic2.id],
  practitioners,
  ownerTeamMemberId: owner.id,
  now: new Date(),
  scale: PROD_SCALE,
  seed: 20260928,
})

console.log(JSON.stringify({ accountId, password, logins, counts }, null, 2))
